#!/usr/bin/env python3
"""Generate mello-core/src/emoji_table.rs from Unicode's emoji-test.txt.

Keeps every fully-qualified emoji up to the Unicode version the bundled font
covers (Twemoji, Mozilla build: 14.0), without skin-tone variants and without
the Component group. Groups map to the picker's eight categories.

Usage:
    python3 tools/emoji/gen_emoji_table.py emoji-test.txt > mello-core/src/emoji_table.rs

Get the file from https://unicode.org/Public/emoji/<version>/emoji-test.txt
"""

import re
import sys

MAX_VERSION = 14.0

# Unicode group -> picker category index (the spec's eight).
CATEGORIES = [
    "Smileys & People",
    "Animals & Nature",
    "Food & Drink",
    "Activities",
    "Travel & Places",
    "Objects",
    "Symbols",
    "Flags",
]
GROUP_TO_CATEGORY = {
    "Smileys & Emotion": 0,
    "People & Body": 0,
    "Animals & Nature": 1,
    "Food & Drink": 2,
    "Activities": 3,
    "Travel & Places": 4,
    "Objects": 5,
    "Symbols": 6,
    "Flags": 7,
}

LINE = re.compile(r"^([0-9A-F ]+?)\s*;\s*fully-qualified\s*#\s*(\S+)\s+E(\d+\.\d+)\s+(.*)$")


def main(path: str) -> None:
    group = None
    rows = []
    for raw in open(path, encoding="utf-8"):
        if raw.startswith("# group:"):
            group = raw.split(":", 1)[1].strip()
            continue
        m = LINE.match(raw.strip())
        if not m or group not in GROUP_TO_CATEGORY:
            continue
        glyph, version, name = m.group(2), float(m.group(3)), m.group(4)
        if version > MAX_VERSION:
            continue
        if "skin tone" in name:
            continue
        rows.append((glyph, name, GROUP_TO_CATEGORY[group]))

    out = sys.stdout
    out.write("//! Generated by tools/emoji/gen_emoji_table.py from Unicode emoji-test.txt.\n")
    out.write(f"//! Fully-qualified emoji up to Emoji {MAX_VERSION}, no skin-tone variants.\n")
    out.write("//! Do not edit by hand.\n\n")
    out.write("/// The picker's categories, in tab order.\n")
    out.write("pub const CATEGORIES: &[&str] = &[\n")
    for c in CATEGORIES:
        out.write(f'    "{c}",\n')
    out.write("];\n\n")
    out.write("/// (emoji, name, category index into `CATEGORIES`), in Unicode order.\n")
    out.write(f"pub static EMOJI: &[(&str, &str, u8)] = &[\n")
    for glyph, name, cat in rows:
        safe = name.replace("\\", "\\\\").replace('"', '\\"')
        out.write(f'    ("{glyph}", "{safe}", {cat}),\n')
    out.write("];\n")
    sys.stderr.write(f"{len(rows)} emoji in {len(CATEGORIES)} categories\n")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
